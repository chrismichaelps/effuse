// Regenerates CAPABILITIES.md from the tested capability matrix.
// Run with: node scripts/generate-capabilities.mjs  (or `pnpm capabilities`)
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { writeFileSync } from 'node:fs';
import { adapterCapabilities } from '../dist/index.js';

const __dirname = dirname(fileURLToPath(import.meta.url));

const FEATURES = [
	['streaming', 'Streaming responses', 'Sends a `ReadableStream` body without buffering it whole.'],
	['requestAbort', 'Request cancellation', 'Surfaces client disconnects on `request.signal`.'],
	['gracefulShutdown', 'Graceful shutdown', '`close()` drains in-flight requests before terminating.'],
	['multipart', 'Multipart bodies', 'Accepts `multipart/form-data` request bodies.'],
	['setCookieMultiValue', 'Multiple Set-Cookie', 'Preserves multiple `Set-Cookie` response headers.'],
	['ephemeralPort', 'Ephemeral port', 'Binds an OS-assigned port via `port: 0`.'],
];

const runtimes = Object.values(adapterCapabilities);
const cell = (value) => (value ? '✅' : '❌');

let md = `# Effuse Server Runtime Compatibility Matrix\n\n`;
md += `> Generated by \`scripts/generate-capabilities.mjs\`. Every cell is validated by the shared conformance suite (\`src/conformance.ts\`); do not edit by hand.\n\n`;
md += `| Capability | ${runtimes.map((r) => r.runtime).join(' | ')} |\n`;
md += `| --- | ${runtimes.map(() => '---').join(' | ')} |\n`;
for (const [key, label] of FEATURES) {
	md += `| ${label} | ${runtimes.map((r) => cell(r[key])).join(' | ')} |\n`;
}
md += `\n## Capability details\n\n`;
for (const [, label, description] of FEATURES) {
	md += `- **${label}** — ${description}\n`;
}
md += `\n## Not yet shipped\n\n`;
md += `- Edge/serverless adapters (Vercel, Netlify, Cloudflare Workers) — a documented adapter contract only; no reference implementation in this release.\n`;
md += `- Per-adapter cold-start, throughput, and memory numbers — tracked with the performance lab (issue #249).\n`;

writeFileSync(resolve(__dirname, '..', 'CAPABILITIES.md'), md);
// eslint-disable-next-line no-console
console.log('[effuse-server] Wrote CAPABILITIES.md');
